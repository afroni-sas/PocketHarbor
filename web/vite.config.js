import { defineConfig } from 'vite'
import preact from '@preact/preset-vite'
import { createHash } from 'node:crypto'
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join, relative, extname } from 'node:path'
import { fileURLToPath } from 'node:url'

// The build goes into the Zig sources and is embedded in the binary, so that
// `zig build` never needs Node.
const outDir = fileURLToPath(new URL('../src/web', import.meta.url))
const manifest = fileURLToPath(new URL('../src/web_assets.zig', import.meta.url))

const types = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.woff2': 'font/woff2',
  '.json': 'application/json',
  '.webmanifest': 'application/manifest+json',
}

// The service worker keeps the interface on the phone's home screen: it
// caches the built files, never the API. Its cache is named after their
// contents, so a new build replaces it.
function writeServiceWorker(files) {
  const urls = files.map((path) => '/' + relative(outDir, path).split('\\').join('/')).filter((u) => u !== '/index.html' && u !== '/sw.js')
  const hash = createHash('sha256')
  for (const file of files) hash.update(readFileSync(file))
  const version = hash.digest('hex').slice(0, 12)
  const path = join(outDir, 'sw.js')
  writeFileSync(
    path,
    `// Generated by web/vite.config.js. Do not edit.
const CACHE = 'pharbor-${version}'
const SHELL = ${JSON.stringify(['/', ...urls])}

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(SHELL)).then(() => self.skipWaiting()))
})

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('pharbor-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  )
})

self.addEventListener('fetch', (e) => {
  const req = e.request
  const url = new URL(req.url)
  if (req.method !== 'GET' || url.origin !== location.origin) return
  // Live data is never served from the cache.
  if (url.pathname.startsWith('/api/') || url.pathname.startsWith('/__pharbor/')) return
  if (req.mode === 'navigate') {
    e.respondWith(fetch(req).catch(() => caches.match('/')))
    return
  }
  e.respondWith(caches.match(req).then((hit) => hit || fetch(req)))
})
`,
  )
  return path
}

function embed() {
  return {
    name: 'pharbor-embed',
    closeBundle() {
      const files = []
      const walk = (dir) => {
        for (const name of readdirSync(dir)) {
          const path = join(dir, name)
          if (statSync(path).isDirectory()) walk(path)
          else files.push(path)
        }
      }
      walk(outDir)
      files.sort()
      files.push(writeServiceWorker(files))
      const entries = files.map((path) => {
        const rel = relative(outDir, path).split('\\').join('/')
        const type = types[extname(path)] || 'application/octet-stream'
        return `    .{ .path = "/${rel}", .type = "${type}", .body = @embedFile("web/${rel}") },`
      })
      writeFileSync(
        manifest,
        `//! Generated by web/vite.config.js from the built interface. Do not edit.\nconst Asset = @import("api.zig").Asset;\n\npub const files = [_]Asset{\n${entries.join('\n')}\n};\n`,
      )
    },
  }
}

export default defineConfig({
  plugins: [preact(), embed()],
  build: {
    outDir,
    emptyOutDir: true,
    assetsDir: 'assets',
    target: 'es2020',
    sourcemap: false,
    chunkSizeWarningLimit: 600,
  },
  server: {
    proxy: {
      '/api': 'http://127.0.0.1:8080',
      '/__pharbor': 'http://127.0.0.1:8080',
    },
  },
})
