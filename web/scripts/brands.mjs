// Writes src/brands.js: the logos the dashboard shows for known images,
// reduced to their title, colour and outline. Simple Icons is CC0.
//   node scripts/brands.mjs
import { writeFileSync } from 'node:fs'
import * as si from 'simple-icons'

const wanted = [
  'siAlpinelinux', 'siCaddy', 'siGhost', 'siGitea', 'siGrafana', 'siMariadb', 'siMinio', 'siMongodb', 'siMysql',
  'siN8n', 'siNatsdotio', 'siNextcloud', 'siNginx', 'siNodedotjs', 'siPostgresql', 'siPython', 'siRabbitmq',
  'siRedis', 'siTraefikproxy', 'siUptimekuma', 'siWordpress', 'siCloudflare',
]

const lines = wanted.map((name) => {
  const icon = si[name]
  if (!icon) throw new Error(`simple-icons has no ${name}`)
  return `export const ${name} = ${JSON.stringify({ title: icon.title, hex: icon.hex, path: icon.path })}`
})
writeFileSync(
  new URL('../src/brands.js', import.meta.url),
  `// Generated by scripts/brands.mjs from Simple Icons (CC0). Do not edit.\n${lines.join('\n')}\n`,
)
console.log(`wrote ${lines.length} logos`)
